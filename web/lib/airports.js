export function buildAirports(extra = []) {
  const list = RAW.map(([code, city, region, lat, lon, tz, intl]) => ({ code, city, region, lat, lon, tz, intl: !!intl }));
  for (const a of extra) {
    if (a && a.code && !list.some((x) => x.code === a.code)) list.push({ intl: false, ...a });
  }
  list.sort((a, b) => a.code.localeCompare(b.code));
  return list;
}

